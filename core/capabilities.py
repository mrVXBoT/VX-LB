def get_capability(engine_id: str) -> Optional[EngineCapabilities]:
    """Retrieve capability definition for a specific engine."""
    eid = engine_id.lower().strip()
    if eid == "gre":
        eid = "gre_ipv4"
    elif eid == "xray":
        eid = "xhttp"
    return CAPABILITIES_CATALOG.get(eid)

def list_all_capabilities() -> Dict[str, dict]:
    """Retrieve all engine capabilities in dictionary form for UI/CLI consumption."""
    return {k: v.to_dict() for k, v in CAPABILITIES_CATALOG.items()}

def is_engine_supported(engine_id: str) -> bool:
    """Check if an engine is verified or experimental (i.e. not unsupported)."""
    cap = get_capability(engine_id)
    return cap is not None and cap.support_status != "unsupported"

def validate_production_readiness(
    engine_id: str,
    is_production: bool = False,
    allow_experimental: bool = False,
) -> Tuple[bool, str]:
    """Production readiness gate.

    Prevents unverified or deprecated tunnel configurations from reaching production:
    - Unsupported engines (e.g. 6to4_anycast per RFC 7526) are strictly blocked in all environments.
    - Verified engines are approved for production and development.
    - Experimental engines are allowed in development/staging/lab environments, but are BLOCKED in
      production unless explicit operational acknowledgement is provided via allow_experimental=True.
    """
    cap = get_capability(engine_id)
    if not cap:
        return False, f"Unknown or unregistered tunnel engine '{engine_id}'."

    if cap.support_status == "unsupported":
        return False, f"Engine '{cap.display_name}' ({engine_id}) is unsupported and disabled by policy: {cap.status_reason}"

    if cap.support_status == "experimental":
        if is_production and not allow_experimental:
            return (
                False,
                f"Engine '{cap.display_name}' ({engine_id}) has 'experimental' status and cannot be deployed in production "
                f"without explicit override (allow_experimental=True). Reason: {cap.status_reason}",
            )
        return True, f"Engine '{cap.display_name}' ({engine_id}) permitted ({'explicit experimental override' if is_production else 'non-production mode'})."

    return True, f"Engine '{cap.display_name}' ({engine_id}) is verified and approved for production."

def get_engine_production_gate_report(engine_id: str) -> Dict[str, Any]:
    """Generates an audit report of an engine's readiness status, evidence, and security disclaimers."""
    cap = get_capability(engine_id)
    if not cap:
        return {
            "engine_id": engine_id,
            "found": False,
            "support_status": "unknown",
            "production_ready": False,
            "reason": f"Unknown engine '{engine_id}'",
        }

    from core.dependency_manifest import get_dependency_manifest
    dep = get_dependency_manifest(engine_id)
    binary_verified = False
    requires_binary = dep is not None
    if dep:
        x86_info = dep.architectures.get("x86_64", {})
        binary_verified = bool(x86_info.get("is_verified") and x86_info.get("sha256"))

    disclaimers = []
    if not cap.requires_encryption:
        disclaimers.append(
            f"Cleartext warning: Engine '{engine_id}' transfers traffic in plaintext without encryption."
        )

    return {
        "engine_id": engine_id,
        "found": True,
        "display_name": cap.display_name,
        "support_status": cap.support_status,
        "production_ready": cap.support_status == "verified",
        "requires_binary": requires_binary,
        "binary_verified": binary_verified,
        "requires_encryption": cap.requires_encryption,
        "encryption_type": cap.encryption_type,
        "kernel_requirements": cap.kernel_requirements,
        "status_reason": cap.status_reason,
        "disclaimers": disclaimers,
    }
