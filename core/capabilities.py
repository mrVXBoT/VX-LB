"""Engine capabilities registry for VX-LB multi-tunnel platform.

Machine-readable registry defining protocols, address
families, directionality, topology, encryption, kernel requirements, MTU bounds,
and support status (verified, experimental, unsupported) with explanatory reasons.
"""
from dataclasses import dataclass, field, asdict
from typing import List, Dict, Optional, Tuple, Any

@dataclass
class EngineCapabilities:
    engine_id: str
    display_name: str
    description: str
    supported_protocols: List[str]  # e.g. ["tcp", "udp"]
    address_families: List[str]     # e.g. ["ipv4", "ipv6"]
    layer: str                      # "L2", "L3", "L4", "L7"
    directionality: str             # "bidirectional", "unidirectional"
    supported_topologies: List[str] # ["1:1", "N:1", "1:M", "N:M"]
    requires_encryption: bool
    encryption_type: str            # "ipsec", "tls", "wireguard", "noise", "none"
    kernel_requirements: List[str]  # e.g. ["gre", "xfrm", "wireguard", "vxlan", "geneve"]
    support_status: str             # "verified", "experimental", "unsupported"
    status_reason: str
    min_mtu: int = 1200
    default_mtu: int = 1400
    overhead_bytes: int = 60
    supports_port_forwarding: bool = True
    supports_raw_link: bool = False
    requires_external_domain: bool = False

    def to_dict(self) -> dict:
        return asdict(self)

